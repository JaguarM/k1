#!/usr/bin/env python3
"""Build-time generator: certificate, ECDSA trick constants, HTTP response blob.

ECDSA trick (zero security): we sign with the fixed nonce k = 1, so
r = x(G) mod n is a constant, and we choose the private key d = r^-1 mod n.
Then s = k^-1 (z + r*d) = z + 1 (mod n): signing is just SHA-256 plus one.
"""
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
R = GX % N
D = pow(R, -1, N)
def tlv(tag, body):
    n = len(body)
    ln = bytes([n]) if n < 128 else bytes([0x80 | ((n.bit_length() + 7) // 8)]) + n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([tag]) + ln + body


def make_cert(key):
    """Smallest X.509 we found browsers accept: v1, no extensions, and no real signature.

    The issuer name differs from the (empty) subject, so the cert is not self-signed: clients
    look for the issuer, don't find it, and report an unknown issuer (bypassable) without ever
    checking the signature, which is therefore an empty BIT STRING. (With issuer == subject,
    Firefox verified the self-signature and refused a dummy one as nssBadCert.)
    """
    sigalg = tlv(0x30, tlv(0x06, bytes.fromhex("2a8648ce3d040302")))  # ecdsa-with-SHA256
    # Compressed point (33 bytes instead of 65): curl, Chrome and Firefox all accept it.
    algid = tlv(0x30, tlv(0x06, bytes.fromhex("2a8648ce3d0201")) + tlv(0x06, bytes.fromhex("2a8648ce3d030107")))
    point = key.public_key().public_bytes(serialization.Encoding.X962,
                                          serialization.PublicFormat.CompressedPoint)
    spki = tlv(0x30, algid + tlv(0x03, b"\x00" + point))
    # (Firefox calls a 1-byte attribute OID like 2.5 bad DER: 2.5.4 is the shortest it takes)
    issuer = tlv(0x30, tlv(0x31, tlv(0x30, tlv(0x06, b"\x55\x04") + tlv(0x13, b""))))  # 2.5.4 = ""
    validity = tlv(0x30, tlv(0x17, b"000101000000Z") + tlv(0x17, b"491231000000Z"))
    tbs = tlv(0x30, tlv(0x02, b"\x01") + sigalg + issuer + validity + tlv(0x30, b"") + spki)
    return tlv(0x30, tbs + sigalg + tlv(0x03, b"\x00"))


def carr(name, data):
    body = ",".join(str(b) for b in data)
    return f"static const u8 {name}[{len(data)}] = {{{body}}};\n"


def main(html_path, out_path):
    key = ec.derive_private_key(D, ec.SECP256R1())
    der = make_cert(key)

    # EncryptedExtensions (empty) + Certificate message, as one constant blob.
    ee = bytes([8, 0, 0, 2, 0, 0])
    entry = len(der).to_bytes(3, "big") + der + b"\0\0"
    body = b"\0" + len(entry).to_bytes(3, "big") + entry
    certmsg = bytes([11]) + len(body).to_bytes(3, "big") + body

    rder = bytes([2, 32]) + R.to_bytes(32, "big")
    assert R >> 255 == 0  # no leading 0x00 needed

    html = open(html_path, "rb").read()
    resp = b"HTTP/1.1 200\nContent-Length:%d\n\n" % len(html) + html  # bare LFs: all clients cope
    resp += b"\x17"  # TLS inner content type (application_data)

    with open(out_path, "w") as f:
        f.write("/* generated by tools/gen.py */\n")
        f.write(carr("eecert", ee + certmsg))
        # CertificateVerify template: 0f 00 00 L | 04 03 | 00 L | 30 L 02 20 <r> 02 L
        f.write(carr("cvt", bytes([0x0f, 0, 0, 0, 4, 3, 0, 0, 0x30, 0]) + rder + bytes([2, 0])))
        f.write(carr("resp", resp))
    # asm CertificateVerify template: s is always a plain 32-byte INTEGER (the server grinds for it)
    cvt = bytes([0x0f, 0, 0, 74, 4, 3, 0, 70, 0x30, 68]) + rder + bytes([2, 32])
    with open(out_path.rsplit(".", 1)[0] + ".inc", "w") as f:  # same blobs for NASM
        for name, data in (("EECERT", ee + certmsg), ("CVT", cvt), ("RESP", resp)):
            f.write(f"{name}: db {','.join(str(b) for b in data)}\n{name}_LEN equ $ - {name}\n")
    with open(out_path.rsplit("/", 1)[0] + "/cert.der", "wb") as f:
        f.write(der)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
